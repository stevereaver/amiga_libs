||||
||||	xpkFBR2_lib.s -- resident module header for
||||	xpkFBR2.library V4.1 "FastBytesRunner" (Froehling)
||||
||||	Single code hunk: "moveq #0,d0 / rts" entry stub
||||	(doubles as the null/return-0 path for ExtFunc and
||||	the three unused sublib slots), RomTag (version 4),
||||	AUTOINIT InitTable (dataSize 0x26), InitStruct data
||||	table, word-offset function table (generated by
||||	genfunctab.py), code, then the STATIC XpkInfo
||||	descriptor + XpkMode list with relocated pointers
||||	(SLZ3/LZW3 convention -- PackerInfo returns its
||||	address via lea).
||||
||||	Hunk map of the original (offset -> contents):
||||	  0x00  moveq #0,d0 / rts       entry stub / null vector
||||	  0x04  RomTag                  AUTOINIT, ver 4, NT_LIBRARY
||||	  0x1e  "$VER: xpkFBR2 V4.1 (1 Oct 2013) ..."
||||	  0x64  InitTable               dataSize 0x26
||||	  0x74  datatab                 InitStruct stream (rev 1)
||||	  0x94  functab                 -1, 10 word offsets, -1
||||	  0xac  LibInit                 stores seglist only
||||	  0xb4  LibOpen / LibClose / LibExpunge
||||	  0x112 XpksPackerInfo          lea descriptor
||||	  0x11a XpksPackChunk           mode dispatch + AutoSize
||||	  0x1cc encoder core            shared RLE machine
||||	  0x2a0 ByteByte count emit     1-byte count
||||	  0x2a4 WordByte count emit     2-byte count
||||	  0x2ac LongByte count emit     4-byte count
||||	  0x2be XpksUnpackChunk         tag dispatch + decoder
||||	  0x35a XpkInfo                 static descriptor
||||	  0x3b2 XpkMode chain           LongByte/WordByte/ByteByte/
||||	                                AutoSize (inline 10-byte descs)
||||	  0x45a "FastRunner" / longname / desc / msg strings
||||	  0x4b0 end
||||

	.section .text

	.globl	_start
_start:
