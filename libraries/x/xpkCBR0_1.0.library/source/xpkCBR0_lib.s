||||	xpkCBR0_lib.s -- resident module header for
||||	xpkCBR0.library V1.0 "Cmp Byte Run 0 Packer"
||||
||||	Single code hunk: "moveq #-1,d0 / rts" entry stub,
||||	a $VER: string using 0xa0 (NBSP) separators, RomTag
||||	(version 1), AUTOINIT InitTable (dataSize 0xaa --
||||	the base embeds the XpkInfo and XpkMode descriptor
||||	blocks, filled in by LibInit at runtime rather than
||||	linked statically), InitStruct data table and all
||||	strings.  The AUTOINIT function table is a
||||	word-offset table generated by genfunctab.py
||||	(functab.s), linked separately.
||||
||||	Hunk map of the original (offset -> contents):
||||	  0x00  moveq #-1,d0 / rts      entry stub (returns -1)
||||	  0x04  "$VER:..."              NBSP-separated version string
||||	  0x4c  RomTag                  AUTOINIT, ver 1, NT_LIBRARY
||||	  0x66  InitTable               dataSize 0xaa
||||	  0x76  datatab                 InitStruct stream
||||	  0x96  "xpkCBR0.library"
||||	  0xa8  "xpkCBR0"               lib_IdString (no version!)
||||	  0xb0  "V1.0 (23-Aug-1992)"    dead string -- unreferenced
||||	  0xc4  functab                 -1, 10 word offsets, -1
||||	  0xdc  LibInit                 fills XpkInfo@+0x28, XpkMode@+0x80
||||	  0xf0  LibOpen / LibClose / LibExpunge
||||	  0x15a null stub               moveq #0,d0 / rts (ExtFunc)
||||	  0x15e XpksPackerInfo          returns base+0x28
||||	  0x168 XpksPackChunk           encoder
||||	  0x27a bare rts                PackFree
||||	  0x27c bare rts                PackReset (also jsr'ed as nop)
||||	  0x27e XpksUnpackChunk         decoder
||||	  0x2f8 bare rts                UnpackFree
||||	  0x2fa descriptor filler       writes descriptors into base
||||	  0x404 empty save/restore rts  dead helper (restores + rts)
||||	  0x410 "CBR0" / longname / desc / msg strings
||||	  0x4b8 end
||||

	.section .text

_start:
	moveq	#-1,d0			| module entry returns -1
	rts

_verstr:
	| original uses 0xa0 (NBSP) separators inside $VER:
	.ascii	"$VER:\xa0xpkCBR0.library\xa0V1.0\xa0\xa9\xa0by\xa0Bilbo\xa01st\xa0of\xa0Hypenosis\xa0on\xa023-Aug-1992."
	.byte	0,0

	.even
_romtag:
	.word	0x4afc			| RT_MATCHWORD
	.long	_romtag			| RT_MATCHTAG
	.long	_endmodule		| RT_ENDSKIP (orig: hunk end)
	.byte	0x80			| RTF_AUTOINIT
	.byte	1			| RT_VERSION
	.byte	9			| NT_LIBRARY
	.byte	0			| RT_PRI
	.long	_libname		| RT_NAME
	.long	_idstr			| RT_IDSTRING
	.long	_inittab		| RT_INIT

||| InitTable: dataSize, funcTable, dataTable, initFunc
_inittab:
	.long	0xaa			| dataSize = sizeof(struct XpkSubBase)
	.long	_functab		| generated word-offset table
	.long	_datatab		| InitStruct data
	.long	_LibInit		| initRoutine

_datatab:
	.byte	0xa0,8			| INITBYTE  ln_Type = NT_LIBRARY
	.byte	9,0
	.byte	0x80,10			| INITLONG  ln_Name
	.long	_libname
	.byte	0xa0,14			| INITBYTE  lib_Flags
	.byte	6,0			|   = LIBF_SUMUSED|LIBF_CHANGED
	.byte	0x90,20			| INITWORD  lib_Version
	.word	1
	.byte	0x90,22			| INITWORD  lib_Revision
	.word	0
	.byte	0x80,24			| INITLONG  lib_IdString
	.long	_idstr
	.long	0			| InitStruct terminator

_libname:
	.ascii	"xpkCBR0.library"
	.byte	0
	.globl	_libname
_idstr:
	.ascii	"xpkCBR0"
	.byte	0			| IdString is bare "xpkCBR0"
	.globl	_idstr
_deadver:
	.ascii	"V1.0 (23-Aug-1992)"	| dead string, unreferenced
	.byte	0

||| strings referenced by the runtime-initialised descriptors
	.globl	_s_name, _s_lname, _s_desc, _s_mode
	.globl	_s_pack, _s_unpack, _s_packed, _s_unpacked, _s_mode
_s_name:
