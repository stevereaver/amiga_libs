	.byte	0
_s_pack:
	.ascii	"Compressing"
	.byte	0
_s_unpack:
	.ascii	"Decompressing"
	.byte	0
_s_packed:
	.ascii	"Compressed"
	.byte	0
_s_unpacked:
	.ascii	"Decompressed"
	.byte	0
_s_mode:
	.ascii	"normal"
	.byte	0,0,0,0			| xm_Description[10] tail

	.end
