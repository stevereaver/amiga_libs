||||	xpkCBR0_lib.s -- resident module header for
||||	xpkCBR0.library V1.1 "Cmp Byte Run 0 Packer"
||||
||||	Single code hunk: "moveq #-1,d0 / rts" entry stub,
||||	RomTag (version 1), AUTOINIT InitTable
||||	(dataSize 0xaa -- the base embeds the XpkInfo and
||||	XpkMode descriptor blocks, filled in by LibInit at
||||	runtime rather than linked statically like
||||	xpkFRLE/xpkRLEN), InitStruct data table and all
||||	strings.  The AUTOINIT function table is a
||||	word-offset table generated by genfunctab.py
||||	(functab.s), linked separately.
||||
||||	Hunk map of the original (offset -> contents):
||||	  0x00  moveq #-1,d0 / rts      entry stub (returns -1!)
||||	  0x04  RomTag                  AUTOINIT, ver 1, NT_LIBRARY
||||	  0x1e  InitTable               dataSize 0xaa
||||	  0x2e  datatab                 InitStruct stream
||||	  0x4e  "xpkCBR0.library"
||||	  0x5e  "xpkCBR0 v1.1\r\n"      (no $VER: cookie)
||||	  0x6d  "CBR0" / longname / desc / msg strings
||||	  0x10a functab                 -1, 10 word offsets, -1
||||	  0x122 LibInit                 fills XpkInfo@+0x28, XpkMode@+0x80
||||	  0x1ce LibOpen / LibClose / LibExpunge
||||	  0x220 null stub               moveq #0,d0 / rts (ExtFunc)
||||	  0x222 bare rts                PackFree/PackReset/UnpackFree
||||	  0x224 XpksPackerInfo          returns base+0x28
||||	  0x22c XpksUnpackChunk         decoder
||||	  0x28e XpksPackChunk           encoder
||||	  0x358 end
||||

	.section .text

_start:
	moveq	#-1,d0			| module entry returns -1
	rts

_romtag:
	.word	0x4afc			| RT_MATCHWORD
	.long	_romtag			| RT_MATCHTAG
	.long	_endmodule		| RT_ENDSKIP (orig: hunk end)
	.byte	0x80			| RTF_AUTOINIT
	.byte	1			| RT_VERSION
	.byte	9			| NT_LIBRARY
	.byte	0			| RT_PRI
	.long	_libname		| RT_NAME
	.long	_idstr			| RT_IDSTRING
	.long	_inittab		| RT_INIT

||| InitTable: dataSize, funcTable, dataTable, initFunc
_inittab:
	.long	0xaa			| dataSize = sizeof(struct XpkSubBase)
	.long	_functab		| generated word-offset table
	.long	_datatab		| InitStruct data
	.long	_LibInit		| initRoutine

_datatab:
	.byte	0xa0,8			| INITBYTE  ln_Type = NT_LIBRARY
	.byte	9,0
	.byte	0x80,10			| INITLONG  ln_Name
	.long	_libname
	.byte	0xa0,14			| INITBYTE  lib_Flags
	.byte	6,0			|   = LIBF_SUMUSED|LIBF_CHANGED
	.byte	0x90,20			| INITWORD  lib_Version
	.word	1
	.byte	0x90,22			| INITWORD  lib_Revision
	.word	1
	.byte	0x80,24			| INITLONG  lib_IdString
	.long	_idstr
	.long	0			| InitStruct terminator

_libname:
	.ascii	"xpkCBR0.library"
	.byte	0
	.globl	_libname
