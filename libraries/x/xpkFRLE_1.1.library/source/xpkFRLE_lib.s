|||
|||	xpkFRLE_lib.s -- resident module header for
|||	xpkFRLE.library V1.1 "Fast Run Length Encoder"
|||
|||	Single code hunk: "moveq #-1,d0 / rts" entry stub, RomTag
|||	(version 1 / revision 1), AUTOINIT InitTable (dataSize 0x26),
|||	InitStruct data table, the XpkInfo/XpkMode descriptor blocks
|||	and all strings.  The AUTOINIT function table is a word-offset
|||	table generated by genfunctab.py (functab.s), linked separately.
|||
|||	Hunk map of the original (offset -> contents):
|||	  0x00  moveq #-1,d0 / rts      entry stub (returns -1!)
|||	  0x04  RomTag                  AUTOINIT, ver 1, NT_LIBRARY
|||	  0x1e  InitTable               dataSize 0x26
|||	  0x2e  functab                 -1, 10 word offsets, -1
|||	  0x46  datatab                 InitStruct stream
|||	  0x66  XpkInfo                 88 bytes
|||	  0xbe  XpkMode                 42 bytes "ByteRun"
|||	  0xe8  "xpkFRLE.library"
|||	  0xf8  "xpkFRLE v1.1\r\n"      (no $VER: cookie)
|||	  0x107 "FRLE" / longname / desc / msg strings
|||	  0x15e initFunc / Open / Close / Expunge
|||	  0x1b8 null stub               moveq #0,d0 / rts
|||	  0x1bc XpksPackerInfo          lea xpkinfo(pc),a0
|||	  0x1c4 XpksPackChunk           encoder
|||	  0x2a4 XpksUnpackChunk         decoder
|||	  0x2f8 end
|||

