#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# xpkDLTA.library.  Reads `nm` output of the pass-1 (dummy) link and
# writes a gas source with the real offsets relative to _functab.
#
# A leading -1 word selects the relative-offset table format;
# entries are word offsets from _functab, terminated by -1.
#
# Usage: python3 genfunctab.py dummy.nm > functab.s

import sys, re

# function table order: 4 system vectors, then the six xpksub LVOs
ORDER = [
    ("_LibOpen",          "-6   Open"),
    ("_LibClose",         "-12  Close"),
    ("_LibExpunge",       "-18  Expunge"),
    ("_LibNull",          "-24  ExtFunc"),
    ("_XpksPackerInfo",   "-30  XpksPackerInfo"),
    ("_XpksPackChunk",    "-36  XpksPackChunk"),
    ("_LibNull",          "-42  XpksPackFree"),
    ("_LibNull",          "-48  XpksPackReset"),
    ("_XpksUnpackChunk",  "-54  XpksUnpackChunk"),
    ("_LibNull",          "-60  XpksUnpackFree"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1")
for name, lvo in ORDER:
    print("\t.word\t0x%04x\t| %s" % ((syms[name] - base) & 0xffff, lvo))
print("\t.word\t-1")
