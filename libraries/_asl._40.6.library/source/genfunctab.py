#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# _asl.library 40.6.  Reads `nm` output of the pass-1 (dummy) link
# and writes a gas source with the real offsets relative to _functab.
#
# Usage: python3 genfunctab.py dummy.nm > functab.s
#
# Original table: -1, ten entries, -1, plus a second pad -1 (the pad
# word lives at the top of datatab.s).  Entries: Open, Close,
# Expunge, a null stub for -24, then six relay stubs that forward to
# asl.library LVOs -30..-60 (names per NDK asl_lib.fd).

import sys, re

ORDER = [
    ("_LibOpen",          "-6   Open"),
    ("_LibClose",         "-12  Close"),
    ("_LibExpunge",       "-18  Expunge"),
    ("_LibNull",          "-24  ExtFunc (stub)"),
    ("_AllocFileRequest", "-30  AllocFileRequest"),
    ("_FreeFileRequest",  "-36  FreeFileRequest"),
    ("_RequestFile",      "-42  RequestFile"),
    ("_AllocAslRequest",  "-48  AllocAslRequest"),
    ("_FreeAslRequest",   "-54  FreeAslRequest"),
    ("_AslRequest",       "-60  AslRequest"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1")
for name, lvo in ORDER:
    print("\t.word\t0x%04x\t| %s" % (syms[name] - base, lvo))
print("\t.word\t-1")
