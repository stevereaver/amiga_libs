#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# freeanim.library 40.29.  Reads `nm` output of the pass-1 (dummy)
# link and writes a gas source with the real offsets relative to
# _functab.
#
# Usage: python3 genfunctab.py dummy.nm > functab.s
#
# The original table is degenerate: all four system vectors point at
# the same null routine, which is also the init function.

import sys, re

# function table order: 4 system vectors, all -> _LibNull
ORDER = [
    ("_LibNull",            "-6   Open"),
    ("_LibNull",            "-12  Close"),
    ("_LibNull",            "-18  Expunge"),
    ("_LibNull",            "-24  ExtFunc"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1")
for name, lvo in ORDER:
    print("\t.word\t0x%04x\t| %s" % (syms[name] - base, lvo))
print("\t.word\t-1")
