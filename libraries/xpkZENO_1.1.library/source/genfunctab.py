#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# xpkZENO.library 1.1.  Reads `nm` output of the pass-1 (dummy) link
# and writes a gas source with the real offsets relative to _functab.

import sys, re

ORDER = [
    ("_LibOpen",          "-6   Open"),
    ("_LibClose",         "-12  Close"),
    ("_LibExpunge",       "-18  Expunge"),
    ("_start",            "-24  ExtFunc (entry stub)"),
    ("_XpksPackerInfo",   "-30  XpksPackerInfo"),
    ("_XpksPackChunk",    "-36  XpksPackChunk"),
    ("_XpksPackFree",     "-42  XpksPackFree"),
    ("_start",            "-48  XpksPackReset (entry stub)"),
    ("_XpksUnpackChunk",  "-54  XpksUnpackChunk"),
    ("_XpksUnpackFree",   "-60  XpksUnpackFree"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1\t\t|| relative-offset marker")
for name, comment in ORDER:
    off = syms[name] - base
    if not (-0x8000 <= off <= 0x7fff):
        sys.exit(f"offset {off:#x} for {name} out of word range")
    print(f"\t.word\t{off}\t\t|| {comment}")
print("\t.word\t-1\t\t|| terminator")
