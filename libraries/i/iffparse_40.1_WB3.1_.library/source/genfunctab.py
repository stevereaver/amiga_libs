#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# iffparse.library.  Reads `nm` output of the pass-1 (dummy) link and
# writes a gas source with the real offsets relative to _functab.
#
# Usage: python3 genfunctab.py dummy.nm > functab.s

import sys, re

# function table order: 4 system vectors, then the 41 iffparse LVOs
# in FD order, including the reserved slot at LVO -96.
ORDER = [
    ("_LibOpen",            "-6   Open"),
    ("_LibClose",           "-12  Close"),
    ("_LibExpunge",         "-18  Expunge"),
    ("_LibNull",            "-24  ExtFunc"),
    ("_AllocIFF",           "-30"),
    ("_OpenIFF",            "-36"),
    ("_ParseIFF",           "-42"),
    ("_CloseIFF",           "-48"),
    ("_FreeIFF",            "-54"),
    ("_ReadChunkBytes",     "-60"),
    ("_WriteChunkBytes",    "-66"),
    ("_ReadChunkRecords",   "-72"),
    ("_WriteChunkRecords",  "-78"),
    ("_PushChunk",          "-84"),
    ("_PopChunk",           "-90"),
    ("_LibNull",            "-96  reserved"),
    ("_EntryHandler",       "-102"),
    ("_ExitHandler",        "-108"),
    ("_PropChunk",          "-114"),
    ("_PropChunks",         "-120"),
    ("_StopChunk",          "-126"),
    ("_StopChunks",         "-132"),
    ("_CollectionChunk",    "-138"),
    ("_CollectionChunks",   "-144"),
    ("_StopOnExit",         "-150"),
    ("_FindProp",           "-156"),
    ("_FindCollection",     "-162"),
    ("_FindPropContext",    "-168"),
    ("_CurrentChunk",       "-174"),
    ("_ParentChunk",        "-180"),
    ("_AllocLocalItem",     "-186"),
    ("_LocalItemData",      "-192"),
    ("_SetLocalItemPurge",  "-198"),
    ("_FreeLocalItem",      "-204"),
    ("_FindLocalItem",      "-210"),
    ("_StoreLocalItem",     "-216"),
    ("_StoreItemInContext", "-222"),
    ("_InitIFF",            "-228"),
    ("_InitIFFasDOS",       "-234"),
    ("_InitIFFasClip",      "-240"),
    ("_OpenClipboard",      "-246"),
    ("_CloseClipboard",     "-252"),
    ("_GoodID",             "-258"),
    ("_GoodType",           "-264"),
    ("_IDtoStr",            "-270"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1")
for name, lvo in ORDER:
    print("\t.word\t0x%04x\t| %s" % (syms[name] - base, lvo))
print("\t.word\t-1")
