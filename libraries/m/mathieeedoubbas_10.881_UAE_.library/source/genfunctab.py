#!/usr/bin/env python3
# genfunctab.py -- emit the AUTOINIT word-offset function table for
# mathieeedoubbas.library.  Reads `nm` output of the pass-1 (dummy)
# link and writes a gas source with the real offsets relative to
# _functab.  Format: -1 flag word, word offsets, -1 terminator.
#
# Usage: python3 genfunctab.py dummy.nm > functab.s

import sys, re

# table order: 4 system vectors, then the 12 mathieeedoubbas LVOs
# in FD order (bias 30).
ORDER = [
    ("_LibOpen",            "-6   Open"),
    ("_LibClose",           "-12  Close"),
    ("_LibExpunge",         "-18  Expunge"),
    ("_LibNull",            "-24  ExtFunc/reserved"),
    ("_IEEEDPFix",          "-30"),
    ("_IEEEDPFlt",          "-36"),
    ("_IEEEDPCmp",          "-42"),
    ("_IEEEDPTst",          "-48"),
    ("_IEEEDPAbs",          "-54"),
    ("_IEEEDPNeg",          "-60"),
    ("_IEEEDPAdd",          "-66"),
    ("_IEEEDPSub",          "-72"),
    ("_IEEEDPMul",          "-78"),
    ("_IEEEDPDiv",          "-84"),
    ("_IEEEDPFloor",        "-90"),
    ("_IEEEDPCeil",         "-96"),
]

syms = {}
for line in open(sys.argv[1]):
    m = re.match(r"([0-9a-fA-F]+)\s+[TtDdBbRr]\s+(\S+)", line.strip())
    if m:
        syms[m.group(2)] = int(m.group(1), 16)

base = syms["_functab"]
missing = [n for n, _ in ORDER if n not in syms]
if missing:
    sys.exit("missing symbols: " + ", ".join(missing))

print("|| generated by genfunctab.py -- do not edit")
print("\t.section .text")
print("\t.globl\t_functab")
print("_functab:")
print("\t.word\t-1")
for name, lvo in ORDER:
    print("\t.word\t0x%04x\t| %s" % (syms[name] - base, lvo))
print("\t.word\t-1")
