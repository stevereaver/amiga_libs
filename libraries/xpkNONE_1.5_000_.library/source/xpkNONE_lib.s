|||
|||	xpkNONE_lib.s -- resident module header for
|||	xpkNONE.library V1.5 (1 Oct 2013) by Dirk Stoecker
|||
|||	Single code hunk, matching the shipped binary's layout:
|||	"moveq #0,d0 / rts" entry stub (doubles as the RT_ENDSKIP
|||	target and as the "return 0" reserved-function target),
|||	RomTag, name/id strings, AUTOINIT InitTable (dataSize 0x26),
|||	the InitStruct data table and the static XpkInfo/XpkMode
|||	descriptor blocks.
|||
|||	The AUTOINIT function table itself is a word-offset table
|||	generated by genfunctab.py (functab.s) and linked separately.
|||

	.section .text

||| executable entry for non-resident loaders: returns 0 as shipped.
||| Also used as the shared "return 0" vector for reserved LVOs.
_start:
	moveq	#0,d0
	rts

_romtag:
	.word	0x4afc			| RT_MATCHWORD
	.long	_romtag			| RT_MATCHTAG
	.long	_start			| RT_ENDSKIP: offset 0 in original
	.byte	0x80			| RTF_AUTOINIT
	.byte	1			| RT_VERSION
	.byte	9			| NT_LIBRARY
	.byte	0			| RT_PRI
	.long	_libname		| RT_NAME
	.long	_idstr			| RT_IDSTRING
	.long	_inittab		| RT_INIT

_libname:
	.ascii	"xpkNONE.library"
	.byte	0
_idstr:
	.ascii	"$VER: xpkNONE V1.5 (1 Oct 2013) by Dirk Stoecker"
	.byte	0xd,0xa,0,0

||| InitTable: dataSize, funcTable, dataTable, initFunc
_inittab:
	.long	0x26			| dataSize = sizeof(struct XpkSubBase)
	.long	_functab		| generated word-offset table
	.long	_datatab		| InitStruct data
	.long	_LibInit		| initRoutine

||| InitStruct data: standard six-entry library node init + terminator.
||| Encodings: 0xA0 off8 = byte, 0x90 off8 = word, 0x80 off8 = long.
_datatab:
	.byte	0xa0,8			| INITBYTE  ln_Type
	.byte	9,0			|   = NT_LIBRARY
	.byte	0x80,10			| INITLONG  ln_Name
	.long	_libname
	.byte	0xa0,14			| INITBYTE  lib_Flags
	.byte	6,0			|   = LIBF_SUMUSED|LIBF_CHANGED
	.byte	0x90,20			| INITWORD  lib_Version
	.word	1
	.byte	0x90,22			| INITWORD  lib_Revision
	.word	5
	.byte	0x80,24			| INITLONG  lib_IdString
	.long	_idstr
	.long	0			| InitStruct terminator

||| XpkInfo descriptor returned by XpksPackerInfo() (LVO -30).
	.even
	.globl	_xpkinfo
_xpkinfo:
	.word	1			| xi_XpkInfoVersion
	.word	1			| xi_LibVersion
	.word	2			| xi_MasterVersion
	.word	0			| xi_ModesVersion
	.long	_s_name			| xi_Name       "NoPacker"
	.long	_s_name			| xi_LongName   "NoPacker"
	.long	_s_desc			| xi_Description
	.long	0x4e4f4e45		| xi_ID         'NONE'
	.long	9			| xi_Flags = XPKIF_PK_CHUNK|XPKIF_UP_CHUNK
	.long	0x8000			| xi_MaxPkInChunk (32K)
	.long	20			| xi_MinPkInChunk
	.long	0x8000			| xi_DefPkInChunk (32K)
	.long	_s_pack			| xi_PackMsg    "Writing"
	.long	_s_unpack		| xi_UnpackMsg  "Reading"
	.long	_s_packed		| xi_PackedMsg  "Wrote"
	.long	_s_unpacked		| xi_UnpackedMsg "Read"
	.word	100			| xi_DefMode
	.word	0			| xi_Pad
	.long	_xpkmode		| xi_ModeDesc
	.long	0,0,0,0,0,0		| xi_Reserved[6]

||| Single XpkMode descriptor, covers modes 0..100.
_xpkmode:
	.long	0			| xm_Next
	.long	100			| xm_Upto
	.long	1			| xm_Flags = XPKMF_A3000SPEED
	.long	0			| xm_PackMemory
	.long	0			| xm_UnpackMemory
	.long	1450			| xm_PackSpeed
	.long	1450			| xm_UnpackSpeed
	.word	0			| xm_Ratio
	.word	0			| xm_ChunkSize
	.ascii	"normal"
	.byte	0,0,0,0			| xm_Description[10]

_s_name:
	.ascii	"NoPacker"
	.byte	0
_s_desc:
	.ascii	"A dummy library that does no compression"
	.byte	0
_s_pack:
	.ascii	"Writing"
	.byte	0
_s_unpack:
	.ascii	"Reading"
	.byte	0
_s_packed:
	.ascii	"Wrote"
	.byte	0
_s_unpacked:
	.ascii	"Read"
	.byte	0
	.even

	.end
