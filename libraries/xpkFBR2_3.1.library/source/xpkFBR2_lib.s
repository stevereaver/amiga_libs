|||||
|||||	xpkFBR2_lib.s -- resident module header for
|||||	xpkFBR2.library 3.1 "FastByteRun" (Froehling, 3.5.2011)
|||||
|||||	Single code hunk: "moveq #-1,d0 / rts" entry stub
|||||	(returns -1, unlike the 4.x entry which returns 0;
|||||	the four unused vectors point at a separate
|||||	moveq #0,d0 / rts null routine), RomTag (version 3),
|||||	AUTOINIT InitTable (dataSize 0x26), InitStruct data
|||||	table, word-offset function table (generated by
|||||	genfunctab.py), code, then the STATIC XpkInfo
|||||	descriptor + linked XpkMode list with relocated
|||||	pointers.
|||||
|||||	Hunk map of the original (offset -> contents):
|||||	  0x00  moveq #-1,d0 / rts    entry stub (never vectored)
|||||	  0x04  RomTag                AUTOINIT, ver 3, NT_LIBRARY
|||||	  0x1e  InitTable             dataSize 0x26
|||||	  0x2e  functab               -1, 10 word offsets, -1
|||||	  0x46  datatab               InitStruct stream (rev 1)
|||||	  0x66  "xpkFBR2.library"
|||||	  0x76  "xpkFBR2 3.1 (3.5.2011)"
|||||	  0x90  XpkInfo               static descriptor
|||||	  0x16a XpkMode chain         Autosizing->LongByte->
|||||	                            WordByte->ByteByte (next-ptrs)
|||||	  0x212 LibInit               stores seglist only
|||||	  0x21a LibOpen / LibClose / LibExpunge
|||||	  0x26c moveq #0,d0 / rts     shared null for -24/-42/-48/-60
|||||	  0x270 XpksPackerInfo        lea descriptor
|||||	  0x27a XpksPackChunk         mode dispatch, 3 encoders
|||||	  0x406 XpksUnpackChunk       tag dispatch + decoder
|||||	  0x4da end
|||||

	.section .text

_start:
	moveq	#-1,d0			| module entry (returns -1!)
	rts
	.globl	_start

_romtag:
	.word	0x4afc			| RT_MATCHWORD
	.long	_romtag			| RT_MATCHTAG
	.long	_endmodule		| RT_ENDSKIP (orig: hunk end)
	.byte	0x80			| RTF_AUTOINIT
	.byte	3			| RT_VERSION
	.byte	9			| NT_LIBRARY
	.byte	0			| RT_PRI
	.long	_libname		| RT_NAME
	.long	_idstr			| RT_IDSTRING
	.long	_inittab		| RT_INIT

|||| InitTable: dataSize, funcTable, dataTable, initFunc
_inittab:
	.long	0x26			| dataSize = sizeof(struct FbrBase)
	.long	_functab		| generated word-offset table
	.long	_datatab		| InitStruct data
	.long	_LibInit		| initRoutine

_datatab:
	.byte	0xa0,8			| INITBYTE  ln_Type = NT_LIBRARY
	.byte	9,0
	.byte	0x80,10			| INITLONG  ln_Name
	.long	_libname
	.byte	0xa0,14			| INITBYTE  lib_Flags
	.byte	6,0			|   = LIBF_SUMUSED|LIBF_CHANGED
	.byte	0x90,20			| INITWORD  lib_Version
	.word	3
	.byte	0x90,22			| INITWORD  lib_Revision
	.word	1
	.byte	0x80,24			| INITLONG  lib_IdString
	.long	_idstr
	.long	0			| InitStruct terminator

_libname:
	.ascii	"xpkFBR2.library"
	.byte	0
	.globl	_libname
_idstr:
	.ascii	"xpkFBR2 3.1 (3.5.2011)"
	.byte	0
	.globl	_idstr

|||| ------------------------------------------------------------
|||| static XpkInfo descriptor (original at 0x90) + XpkMode chain
|||| ------------------------------------------------------------

	.even
	.globl	_xpkinfo
_xpkinfo:
	.word	1			| xi_XpkInfoVersion
	.word	3			| xi_LibVersion
	.word	2			| xi_MasterVersion
	.word	0			| xi_ModesVersion
	.long	_s_name			| xi_Name "FastByteRun"
	.long	_s_lname		| xi_LongName
	.long	_s_desc			| xi_Description
	.long	0x46425232		| xi_ID 'FBR2'
	.long	0x8009			| xi_Flags
	.long	0x7fffffff		| xi_MaxPkInChunk
	.long	7			| xi_MinPkInChunk
	.long	0x7fff			| xi_DefPkInChunk (32K)
	.long	_s_running		| xi_PackMsg "Running"
	.long	_s_running		| xi_UnpackMsg "Running" (dup!)
	.long	_s_ready		| xi_PackedMsg "Ready"
	.long	_s_steady		| xi_UnpackedMsg "Steady"
	.word	100			| xi_DefMode = ByteByte
	.word	0			| pad
	.long	_modes			| xi_ModeDesc (list head)
	.long	0,0,0,0,0,0		| xi_Reserved[6]

|||| XpkMode chain (42B each): next, upto, flags, packmem,
|||| unpackmem, packspeed, unpackspeed, ratio(w), chunksize(w),
|||| desc[10].  Note the reversed order vs V4.1 (AutoSize is the
|||| head here) and the odd Autosizing field values.
	.globl	_modes
_modes:
	.long	_mode2
	.long	0			| Autosizing: upto 0 (!)
	.long	0			| flags 0
	.long	1			| packmem
	.long	1			| unpackmem
	.long	1			| packspeed 1 (marketing)
	.long	0x12c			| unpackspeed 300
	.word	0			| ratio 0
	.word	0x578			| chunksize 1400
	.ascii	"Autosizing"		| 10 chars, no NUL
_mode2:
	.long	_mode3
	.long	33			| LongByte upto
	.long	1
	.long	1
	.long	1
	.long	0x12c			| packspeed 300
	.long	0x578			| unpackspeed 1400
	.word	0x64			| ratio 100
	.word	0			| chunksize
	.ascii	"LongByte"
	.byte	0,0
_mode3:
	.long	_mode4
	.long	67			| WordByte upto
	.long	1
	.long	1
	.long	1
	.long	0x12c
	.long	0x578
	.word	0x64
	.word	0
	.ascii	"WordByte"
	.byte	0,0
_mode4:
	.long	0			| ByteByte (list end)
	.long	100			| upto 100
	.long	1
	.long	1
	.long	1
	.long	0x12c
	.long	0x578
	.word	0x64
	.word	0
	.ascii	"ByteByte"
	.byte	0,0

_s_name:
	.ascii	"FastByteRun"
	.byte	0
