||||||
||||||	xpkILZR_lib.s -- resident module header for
||||||	xpkILZR.library 1.5 "Incremental LZ-Renau" (Jose Reanu,
||||||	1 Oct 2013)
||||||
||||||	Single code hunk: "moveq #0,d0 / rts" entry stub,
||||||	RomTag (version 1), AUTOINIT InitTable (dataSize 0x26),
||||||	InitStruct data table, word-offset function table
||||||	(generated by genfunctab.py; the two null slots use a
||||||	BACKWARD offset to the entry stub), code, then the
||||||	static XpkInfo descriptor + single-node XpkMode list
||||||	with relocated pointers.
||||||
||||||	Hunk map of the original (offset -> contents):
||||||	  0x00  moveq #0,d0 / rts     entry stub / null vector
||||||	  0x04  RomTag                AUTOINIT, ver 1
||||||	  0x1e  InitTable             dataSize 0x26
||||||	  0x2e  datatab               InitStruct stream (rev 5)
||||||	  0x42  name/idstr
||||||	  0x5e  functab               -1, 10 word offsets, -1
||||||	  0x74  LibInit..LibExpunge
||||||	  0xe2  XpksPackFree          FreeMem(xsp_Sub[0]-4)
||||||	  0xfc  XpksPackReset         clears head[] table
||||||	  0x132 XpksPackerInfo        lea descriptor
||||||	  0x13c XpksPackChunk         hash-chain LZSS encoder
||||||	  0x4b4 XpksUnpackChunk       bit-reader decoder
||||||	  0x524 XpkInfo + XpkMode + strings
||||||	  0x568 end
||||||

	.section .text

_start:
	moveq	#0,d0			| module entry + null vector
	rts
	.globl	_start

_romtag:
	.word	0x4afc			| RT_MATCHWORD
	.long	_romtag			| RT_MATCHTAG
	.long	_endmodule		| RT_ENDSKIP (orig: hunk end)
	.byte	0x80			| RTF_AUTOINIT
	.byte	1			| RT_VERSION
	.byte	9			| NT_LIBRARY
	.byte	0			| RT_PRI
	.long	_libname		| RT_NAME
	.long	_idstr			| RT_IDSTRING
	.long	_inittab		| RT_INIT

||||| InitTable: dataSize, funcTable, dataTable, initFunc
_inittab:
	.long	0x26			| dataSize = sizeof(struct IlzrBase)
	.long	_functab		| generated word-offset table
	.long	_datatab		| InitStruct data
	.long	_LibInit		| initRoutine

_datatab:
	.byte	0xa0,8			| INITBYTE  ln_Type = NT_LIBRARY
	.byte	9,0
	.byte	0x80,10			| INITLONG  ln_Name
	.long	_libname
	.byte	0xa0,14			| INITBYTE  lib_Flags
	.byte	6,0			|   = LIBF_SUMUSED|LIBF_CHANGED
	.byte	0x90,20			| INITWORD  lib_Version
	.word	1
	.byte	0x90,22			| INITWORD  lib_Revision
	.word	5
	.byte	0x80,24			| INITLONG  lib_IdString
	.long	_idstr
	.long	0			| InitStruct terminator

_libname:
	.ascii	"xpkILZR.library"
	.byte	0
	.globl	_libname
_idstr:
	.ascii	"$VER: xpkILZR V1.5 (1 Oct 2013) by Jose Reanu"
	.byte	13,10,0
	.globl	_idstr

||||| ------------------------------------------------------------
||||| static XpkInfo descriptor (original at 0x524) + XpkMode node
||||| ------------------------------------------------------------

	.even
	.globl	_xpkinfo
_xpkinfo:
	.word	1			| xi_XpkInfoVersion
	.word	1			| xi_LibVersion
	.word	2			| xi_MasterVersion
	.word	0			| xi_ModesVersion
	.long	_s_name			| xi_Name "ILZR"
	.long	_s_lname		| xi_LongName
	.long	_s_desc			| xi_Description
	.long	0x494c5a52		| xi_ID 'ILZR'
	.long	9			| xi_Flags
	.long	0x4000			| xi_MaxPkInChunk 16384
	.long	0			| xi_MinPkInChunk
	.long	0x4000			| xi_DefPkInChunk
	.long	_s_pack			| xi_PackMsg "Compressing"
	.long	_s_unpack		| xi_UnpackMsg "Expanding"
	.long	_s_packed		| xi_PackedMsg "Packed"
	.long	_s_unpacked		| xi_UnpackedMsg "Unpacked"
	.word	100			| xi_DefMode
	.word	0			| pad
	.long	_mode			| xi_ModeDesc (single node)
	.long	0,0,0,0,0,0		| xi_Reserved[6]

||||| XpkMode (42B): next, upto, flags, packmem, unpackmem,
||||| packspeed, unpackspeed, ratio(w), chunksize(w), desc[10]
	.globl	_mode
_mode:
	.long	0			| next = end of list
	.long	100			| upto
	.long	1			| flags
	.long	0x18004			| packmem = WORKMEM_SIZE
	.long	0			| unpackmem
	.long	0x1c			| packspeed 28
	.long	0x104			| unpackspeed 260
	.word	0x181			| ratio 385
	.word	0			| chunksize
	.ascii	"fast"
	.byte	0,0,0,0,0,0		| desc[10]

